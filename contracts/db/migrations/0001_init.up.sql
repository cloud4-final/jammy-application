CREATE SCHEMA jammy;

CREATE TABLE jammy.assets (
    asset_id text PRIMARY KEY,
    tenant_id text NOT NULL,
    profile text NOT NULL CHECK (profile IN ('solar', 'synth-small', 'synth-large')),
    capacity_kw numeric(14,3) NOT NULL
);

CREATE TABLE jammy.raw_events (
    event_id text NOT NULL,
    routing_key text NOT NULL,
    profile text NOT NULL CHECK (profile IN ('solar', 'synth-small', 'synth-large')),
    schema_version integer NOT NULL,
    event_time timestamptz NOT NULL,
    received_at timestamptz NOT NULL DEFAULT now(),
    ingest_id text NOT NULL,
    primary_value double precision NOT NULL,
    payload bytea NOT NULL,
    PRIMARY KEY (event_id, received_at)
) PARTITION BY RANGE (received_at);

CREATE TABLE jammy.quarantine (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    received_at timestamptz NOT NULL DEFAULT now(),
    ingest_id text NOT NULL,
    batch_id text NOT NULL,
    reason text NOT NULL,
    raw bytea NOT NULL
);

CREATE TABLE jammy.processed_batches (
    consumer text NOT NULL,
    batch_id text NOT NULL,
    processed_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (consumer, batch_id)
);

CREATE TABLE jammy.consumer_cursor (
    consumer text PRIMARY KEY,
    last_received_at timestamptz NOT NULL,
    last_event_id text NOT NULL
);

CREATE TABLE jammy.latest_state (
    routing_key text PRIMARY KEY,
    profile text NOT NULL CHECK (profile IN ('solar', 'synth-small', 'synth-large')),
    primary_value double precision NOT NULL,
    event_time timestamptz NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE jammy.summary_1m (
    profile text NOT NULL CHECK (profile IN ('solar', 'synth-small', 'synth-large')),
    routing_key text NOT NULL,
    minute timestamptz NOT NULL,
    count bigint NOT NULL,
    sum double precision NOT NULL,
    min double precision NOT NULL,
    max double precision NOT NULL,
    PRIMARY KEY (profile, routing_key, minute)
) PARTITION BY RANGE (minute);

CREATE TABLE jammy.incidents (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    routing_key text NOT NULL,
    profile text NOT NULL CHECK (profile IN ('solar', 'synth-small', 'synth-large')),
    kind text NOT NULL CHECK (kind IN ('drop', 'over_capacity')),
    window_start timestamptz NOT NULL,
    window_end timestamptz NOT NULL,
    details jsonb NOT NULL,
    UNIQUE (routing_key, kind, window_start)
);

CREATE TABLE jammy.instructions (
    instruction_id text PRIMARY KEY,
    body bytea NOT NULL,
    body_sha256 text NOT NULL,
    target_reduction_kw numeric(14,3) NOT NULL,
    valid_from timestamptz NOT NULL,
    valid_until timestamptz NOT NULL,
    status text NOT NULL CHECK (status IN (
        'accepted', 'dispatching', 'dispatched', 'partially_dispatched', 'expired'
    )),
    source text NOT NULL CHECK (source IN ('https', 'sqs')),
    received_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE jammy.commands (
    command_id uuid NOT NULL,
    instruction_id text NOT NULL REFERENCES jammy.instructions (instruction_id),
    asset_id text NOT NULL,
    reduction_kw numeric(14,3) NOT NULL,
    generation bigint NOT NULL,
    epoch bigint NOT NULL,
    status text NOT NULL CHECK (status IN ('pending', 'acked', 'stale_epoch', 'timeout', 'error')),
    sent_at timestamptz,
    acked_at timestamptz,
    UNIQUE (instruction_id, asset_id)
);

CREATE TABLE jammy.leader_generation (
    name text PRIMARY KEY,
    generation bigint NOT NULL,
    holder text NOT NULL,
    acquired_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE jammy.compliance (
    instruction_id text NOT NULL REFERENCES jammy.instructions (instruction_id),
    asset_id text NOT NULL,
    expected_kw numeric(14,3) NOT NULL,
    observed_reduction_kw numeric(14,3) NOT NULL,
    verdict text NOT NULL CHECK (verdict IN ('met', 'not_met', 'no_data')),
    checked_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (instruction_id, asset_id)
);

CREATE TABLE jammy.archive_exports (
    partition_name text PRIMARY KEY,
    s3_key text NOT NULL,
    rows bigint NOT NULL,
    sha256 text NOT NULL,
    exported_at timestamptz NOT NULL DEFAULT now(),
    dropped_at timestamptz
);

CREATE FUNCTION jammy.ensure_partitions(ahead interval, behind interval DEFAULT '24 hours')
RETURNS integer
LANGUAGE plpgsql
AS $$
DECLARE
    now_utc timestamp := now() AT TIME ZONE 'UTC';
    partition_start timestamp;
    partition_end timestamp;
    child_name text;
    created integer := 0;
BEGIN
    PERFORM pg_advisory_xact_lock(hashtext('jammy'), hashtext('ensure_partitions'));

    FOR partition_start IN
        SELECT generate_series(
            date_trunc('hour', now_utc),
            date_trunc('hour', now_utc + ahead),
            interval '1 hour'
        )
    LOOP
        child_name := 'raw_events_' || to_char(partition_start, 'YYYYMMDDHH24');
        IF to_regclass(format('jammy.%I', child_name)) IS NULL THEN
            partition_end := partition_start + interval '1 hour';
            EXECUTE format(
                'CREATE TABLE jammy.%I PARTITION OF jammy.raw_events FOR VALUES FROM (%L) TO (%L)',
                child_name, partition_start AT TIME ZONE 'UTC', partition_end AT TIME ZONE 'UTC'
            );
            created := created + 1;
        END IF;
    END LOOP;

    FOR partition_start IN
        SELECT generate_series(
            date_trunc('day', now_utc - behind),
            date_trunc('day', now_utc + ahead),
            interval '1 day'
        )
    LOOP
        child_name := 'summary_1m_' || to_char(partition_start, 'YYYYMMDD');
        IF to_regclass(format('jammy.%I', child_name)) IS NULL THEN
            partition_end := partition_start + interval '1 day';
            EXECUTE format(
                'CREATE TABLE jammy.%I PARTITION OF jammy.summary_1m FOR VALUES FROM (%L) TO (%L)',
                child_name, partition_start AT TIME ZONE 'UTC', partition_end AT TIME ZONE 'UTC'
            );
            created := created + 1;
        END IF;
    END LOOP;

    RETURN created;
END;
$$;

SELECT jammy.ensure_partitions('3 hours', '24 hours');
